"""Shared files and calendar tool for the placement demos."""

from __future__ import annotations

from datetime import date, datetime, time, timedelta
from pathlib import Path


ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
OUTPUTS = ROOT / "outputs"
DEFAULT_RESUME = DATA / "sample_resume.txt"
DEFAULT_JOB = DATA / "sample_job_description.txt"


def read_text(path: str | Path, limit: int = 8_000) -> str:
    text = Path(path).expanduser().read_text(encoding="utf-8").strip()
    if not text:
        raise ValueError(f"File is empty: {path}")
    return text[:limit]


def placement_context(resume_path: str | Path, job_path: str | Path) -> str:
    return f"RESUME:\n{read_text(resume_path)}\n\nJOB DESCRIPTION:\n{read_text(job_path)}"


def _ics_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def create_preparation_schedule(tasks: list[str], start_date: str, study_days: int = 14) -> dict:
    """Create an importable calendar schedule for placement preparation.

    Args:
        tasks: Prioritized learning and practice tasks, ordered by importance.
        start_date: First study date in YYYY-MM-DD format.
        study_days: Number of calendar days available for preparation.

    Returns:
        Calendar file path and number of scheduled sessions.
    """
    if not tasks:
        return {"error": "No tasks supplied"}
    start = date.fromisoformat(start_date)
    days = min(max(study_days, 1), 30)
    selected = [task.strip()[:120] for task in tasks[:8] if task.strip()]
    if not selected:
        return {"error": "No non-empty tasks supplied"}
    OUTPUTS.mkdir(exist_ok=True)
    calendar_path = OUTPUTS / "placement_preparation.ics"
    stamp = datetime.now().strftime("%Y%m%dT%H%M%S")
    events = []
    for index in range(days):
        session_date = start + timedelta(days=index)
        begins = datetime.combine(session_date, time(18, 0))
        ends = begins + timedelta(hours=1)
        task = selected[index % len(selected)]
        events.extend([
            "BEGIN:VEVENT",
            f"UID:placement-{index}-{stamp}@st-peters-demo",
            f"DTSTAMP:{stamp}",
            f"DTSTART:{begins.strftime('%Y%m%dT%H%M%S')}",
            f"DTEND:{ends.strftime('%Y%m%dT%H%M%S')}",
            f"SUMMARY:{_ics_escape('Placement Prep: ' + task)}",
            "DESCRIPTION:Generated by the Gemini placement preparation agent.",
            "END:VEVENT",
        ])
    content = "\r\n".join(["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//ST Peters//Placement Agent//EN", *events, "END:VCALENDAR", ""])
    calendar_path.write_text(content, encoding="utf-8")
    return {"calendar_file": str(calendar_path), "sessions": days, "start_date": start_date}
